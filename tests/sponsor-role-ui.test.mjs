test('Mainnet sponsor review UI separates sponsor identity and signs only request-specific approval text', () => {
  assert.ok(app.includes('const [mainnetSponsorIdentity, setMainnetSponsorIdentity]'))
  assert.ok(app.includes("'/api/tron/sponsorship/mainnet-direct/review-queue?limit=50'"))
  assert.ok(app.includes("'/approval-challenge'"))
  assert.ok(app.includes("'/approve'"))
  assert.ok(app.includes("tronWeb.trx.signMessageV2(challenge.message)"))
  assert.ok(app.includes('Review every field before signing'))
  assert.ok(app.includes('This is a sponsor approval statement only, not a TRON transaction'))
  assert.ok(app.includes('It does not authorize fees, reserve funds, create a transaction or enable payout execution'))
  assert.ok(app.includes('mainnetSponsorIdentity.address'))
  assert.ok(app.includes('SPONSOR_ASSET_MAINNET_ADDRESS'))
  const start = app.indexOf('const signMainnetSponsorApproval = async () =>')
  const end = app.indexOf('const loadMainnetDirectSponsorReadiness = async () =>', start)
  assert.ok(start >= 0 && end > start)
  const signing = app.slice(start, end)
  assert.ok(signing.includes('signMessageV2(challenge.message)'))
  assert.ok(signing.includes('/approve'))
  assert.equal(signing.includes('sendTrx('), false)
  assert.equal(signing.includes('sendRawTransaction'), false)
})


