import { useCallback, useEffect, useState } from 'react'
import './owner-account-security.css'

export default function OwnerAccountSecurity({ wallet, onConnect }) {
  const auth = wallet?.authClient
  const [sessions, setSessions] = useState([])
  const [loading, setLoading] = useState(false)
  const [busy, setBusy] = useState(false)
  const [currentPassword, setCurrentPassword] = useState('')
  const [newPassword, setNewPassword] = useState('')
  const [confirmPassword, setConfirmPassword] = useState('')
  const [recoveryMode, setRecoveryMode] = useState(false)
  const [recoveryToken, setRecoveryToken] = useState('')
  const [recoveryPassword, setRecoveryPassword] = useState('')
  const [recoveryConfirmPassword, setRecoveryConfirmPassword] = useState('')
  const [error, setError] = useState('')
  const [notice, setNotice] = useState('')

  const refresh = useCallback(async () => {
    if (!auth) return
    setLoading(true); setError('')
    try {
      const result = await auth.sessions()
      setSessions(Array.isArray(result.sessions) ? result.sessions : [])
    } catch (cause) { setError(cause?.message || 'OWNER_SESSION_LIST_UNAVAILABLE') }
    finally { setLoading(false) }
  }, [auth])

  useEffect(() => { void refresh() }, [refresh])

  async function changePassword(event) {
    event.preventDefault()
    setError(''); setNotice('')
    if (newPassword.length < 12) { setError('Use a password with at least 12 characters.'); return }
    if (newPassword !== confirmPassword) { setError('The new password confirmation does not match.'); return }
    setBusy(true)
    try {
      await auth.changePassword(currentPassword, newPassword)
      setCurrentPassword(''); setNewPassword(''); setConfirmPassword('')
      setNotice('Owner password changed. All previous sessions were revoked and this browser received a fresh session.')
      await refresh()
    } catch (cause) { setError(cause?.message || 'OWNER_PASSWORD_CHANGE_FAILED') }
    finally { setBusy(false) }
  }

  async function recoverPassword(event) {
    event.preventDefault()
    setError(''); setNotice('')
    if (recoveryToken.trim().length < 32) { setError('Enter the one-time Owner recovery token generated by the server operator.'); return }
    if (recoveryPassword.length < 12) { setError('Use a new password with at least 12 characters.'); return }
    if (recoveryPassword !== recoveryConfirmPassword) { setError('The new password confirmation does not match.'); return }
    setBusy(true)
    try {
      await auth.recoverPassword(recoveryToken.trim(), recoveryPassword)
      setRecoveryToken(''); setRecoveryPassword(''); setRecoveryConfirmPassword('')
      setNotice('Owner password recovered. The one-time token was consumed and all previous Owner sessions were revoked. Sign in again.')
      setSessions([])
      setRecoveryMode(false)
    } catch (cause) { setError(cause?.message || 'OWNER_PASSWORD_RECOVERY_FAILED') }
    finally { setBusy(false) }
  }

  async function revokeOthers() {
    setBusy(true); setError(''); setNotice('')
    try {
      const result = await auth.revokeOtherSessions()
      setNotice('Revoked ' + Number(result.revokedCount || 0) + ' other Owner session(s).')
      await refresh()
    } catch (cause) { setError(cause?.message || 'OWNER_SESSION_REVOCATION_FAILED') }
    finally { setBusy(false) }
  }

  async function revokeOne(sessionId) {
    setBusy(true); setError(''); setNotice('')
    try {
      const result = await auth.revokeSession(sessionId)
      setNotice(result.revoked ? 'Selected Owner session revoked.' : 'The selected session was already inactive.')
      await refresh()
    } catch (cause) { setError(cause?.message || 'OWNER_SESSION_REVOCATION_FAILED') }
    finally { setBusy(false) }
  }

  if (!auth) return <section className="owner-security-card">
    <h2>Owner account security</h2>
    <p>Unlock the backend-managed Owner account to manage sessions and change its password.</p>
    <button type="button" onClick={onConnect}>Unlock Owner workspace</button>
  </section>

  return <div className="owner-security-layout">
    <section className="owner-security-card">
      <div className="owner-security-heading"><div><span>TRON TRANSFER · ACCOUNT PROTECTION</span><h2>Owner account security</h2><p>Backend-managed password account · no browser private key</p></div></div>
      <p className="owner-security-note">Changing your password revokes every existing Owner session and issues a fresh session to this browser. Recovery requires a separate one-time token generated by the server operator.</p>
      <form onSubmit={changePassword} className="owner-security-form">
        <label>Current password<input type="password" autoComplete="current-password" value={currentPassword} onChange={e=>setCurrentPassword(e.target.value)} required/></label>
        <label>New password<input type="password" autoComplete="new-password" minLength={12} value={newPassword} onChange={e=>setNewPassword(e.target.value)} required/></label>
        <label>Confirm new password<input type="password" autoComplete="new-password" minLength={12} value={confirmPassword} onChange={e=>setConfirmPassword(e.target.value)} required/></label>
        <button type="submit" disabled={busy || currentPassword.length===0 || newPassword.length<12 || confirmPassword.length<12}>{busy?'Updating…':'Change Owner password'}</button>
      </form>
      <button className="owner-security-secondary" type="button" disabled={busy} onClick={() => { setRecoveryMode(value => !value); setRecoveryToken(''); setRecoveryPassword(''); setRecoveryConfirmPassword(''); setError(''); setNotice('') }}>{recoveryMode ? 'Cancel password recovery' : 'Recover Owner password'}</button>
      {recoveryMode && <form onSubmit={recoverPassword} className="owner-security-form owner-security-recovery-form">
        <label>One-time Owner recovery token<input type="password" autoComplete="off" value={recoveryToken} onChange={e=>setRecoveryToken(e.target.value)} minLength={32} required/><small>Generate this token on the trusted server using the Owner recovery-token command. It is single-use and role-scoped.</small></label>
        <label>New Owner password<input type="password" autoComplete="new-password" minLength={12} value={recoveryPassword} onChange={e=>setRecoveryPassword(e.target.value)} required/></label>
        <label>Confirm new Owner password<input type="password" autoComplete="new-password" minLength={12} value={recoveryConfirmPassword} onChange={e=>setRecoveryConfirmPassword(e.target.value)} required/></label>
        <button type="submit" disabled={busy || recoveryToken.trim().length<32 || recoveryPassword.length<12 || recoveryPassword!==recoveryConfirmPassword}>{busy?'Recovering…':'Confirm Owner password recovery'}</button>
      </form>}
    </section>
    <section className="owner-security-card">
      <div className="owner-security-session-heading"><div><h3>Active Owner sessions</h3><p>Only session metadata is shown. Session tokens are never returned.</p></div><button type="button" onClick={refresh} disabled={loading}>{loading?'Refreshing…':'Refresh'}</button></div>
      <div className="owner-security-session-list">
        {sessions.length===0 && <p className="owner-security-muted">{loading?'Loading active sessions…':'No active sessions were returned.'}</p>}
        {sessions.map(session=><article key={session.session_id} className="owner-security-session">
          <div><strong>{session.current?'This browser':'Other browser session'}</strong><span>Session #{session.session_id}</span><small>Last active: {session.last_seen_at ? new Date(session.last_seen_at).toLocaleString() : 'Unknown'} · Expires: {session.expires_at ? new Date(session.expires_at).toLocaleString() : 'Unknown'}</small></div>
          {!session.current && <button type="button" disabled={busy} onClick={()=>revokeOne(session.session_id)}>Revoke</button>}
        </article>)}
      </div>
      <button className="owner-security-secondary" type="button" disabled={busy || sessions.filter(s=>!s.current).length===0} onClick={revokeOthers}>Revoke all other sessions</button>
    </section>
    {error && <p className="owner-security-error" role="alert">{error}</p>}
    {notice && <p className="owner-security-success" role="status">{notice}</p>}
  </div>
}
